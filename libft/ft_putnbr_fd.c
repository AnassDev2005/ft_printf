#include "libft.h"

void	ft_putnbr_fd(int c, int fd)
{
	long	n;
	char	d;

	n = (long)c;
	if (n < 0)
	{
		n = -n;
		write(fd, "-", 1);
	}
	if (n > 9)
	{
		ft_putnbr_fd(n / 10, fd);
	}
	d = (n % 10) + '0';
	write(fd, &d, 1);
}
